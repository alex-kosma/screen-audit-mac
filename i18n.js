let LANG = "en";

function t(key, vars = {}) {
  const s = STRINGS[LANG][key] ?? STRINGS.en[key] ?? key;
  return typeof s === "function" ? s(vars) : s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? "");
}

function fmtMin(m) {
  return m >= 60 ? t("hm", { h: Math.floor(m / 60), m: String(m % 60).padStart(2, "0") }) : t("min", { m });
}

// Pages start hidden (html.i18n-pending) so English never flashes before Ukrainian.
function applyLang(lang) {
  LANG = STRINGS[lang] ? lang : "en";
  document.documentElement.lang = LANG;
  document.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll("[data-i18n-ph]").forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  document.querySelectorAll("[data-i18n-title]").forEach(el => { el.title = t(el.dataset.i18nTitle); });
  document.documentElement.classList.remove("i18n-pending");
}
